def maximum_prior_overlap() -> float:
    maximum = 0.0
    for path in Path("data/eval").glob("*.json"):
        if path == OUTPUT:
            continue
        for previous in json.loads(path.read_text()).get("cases", []):
            right = terms(previous["question"])
            for item in CASES:
                left = terms(str(item["question"]))
                maximum = max(maximum, len(left & right) / len(left | right))
    return maximum


def main() -> None:
    if len(CASES) != 60:
        raise SystemExit(f"expected 60 cases, found {len(CASES)}")
    payload = {
        "dataset_id": DATASET_ID,
        "dataset_version": DATASET_ID,
        "corpus_version": "acmeai-v1",
        "generation_method": "manual-corpus-grounded-v1",
        "cases": CASES,
    }
    OUTPUT.write_text(json.dumps(payload, indent=2) + "\n")
    digest = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    overlap = maximum_prior_overlap()
    print(json.dumps({"dataset_hash": digest, "maximum_prior_overlap": overlap, "case_count": len(CASES)}))
    if overlap >= 0.5:
        raise SystemExit("overlap guard failed")


if __name__ == "__main__":
    main()
