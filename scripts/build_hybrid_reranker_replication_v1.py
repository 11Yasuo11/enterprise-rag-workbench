def case(
    case_id: str,
    category: str,
    question: str,
    *,
    documents: list[str] | None = None,
    versions: dict[str, str] | None = None,
    answer: str | None = None,
    facts: list[str] | None = None,
    fact_ids: list[str] | None = None,
    forbidden: list[str] | None = None,
    access: str = "ALLOW_REQUIRED",
    answerable: bool = True,
    principal: dict[str, object] | None = None,
    security: list[str] | None = None,
) -> dict[str, object]:
    payload: dict[str, object] = {
        "case_id": case_id,
        "category": category,
        "question": question,
        "required_document_ids": documents or [],
        "required_chunk_ids": [],
        "required_version_ids": versions or {},
        "required_fact_ids": fact_ids or [],
        "expected_facts": facts or [],
        "expected_answer": answer,
        "forbidden_document_ids": forbidden or [],
        "expected_access_behavior": access,
        "expected_answerability": answerable,
        "should_abstain": not answerable,
        "expected_document_ids": documents or [],
        "expected_versions": versions or {},
        "security_checks": security or [],
    }
    if principal:
        payload["principal"] = principal
    return payload


