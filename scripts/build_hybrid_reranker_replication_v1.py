def pairwise_maximum(left_questions: list[str], right_questions: list[str]) -> float:
    maximum = 0.0
    left_terms = [terms(question) for question in left_questions]
    right_terms = [terms(question) for question in right_questions]
    for left in left_terms:
        for right in right_terms:
            maximum = max(maximum, len(left & right) / len(left | right))
    return maximum


def maximum_prior_overlap() -> tuple[float, dict[str, float]]:
    new_questions = [str(item["question"]) for item in CASES]
    overall = 0.0
    per_file: dict[str, float] = {}
    for path in sorted(Path("data/eval").glob("*.json")):
        if path == OUTPUT:
            continue
        previous = [item["question"] for item in json.loads(path.read_text()).get("cases", [])]
        score = pairwise_maximum(new_questions, previous)
        per_file[path.name] = score
        overall = max(overall, score)
    return overall, per_file


def main() -> None:
    if len(CASES) != 80:
        raise SystemExit(f"expected 80 cases, found {len(CASES)}")
    expected = {
        "multidoc_two": 10,
        "multidoc_three": 40,
        "near_duplicate": 8,
        "exact_identifier": 6,
        "version_region": 6,
        "semantic_paraphrase": 4,
        "acl_sensitive": 3,
        "partial_no_answer": 3,
    }
    counts = {key: sum(item["category"] == key for item in CASES) for key in expected}
    if counts != expected:
        raise SystemExit(f"distribution mismatch: {counts}")
    if len({item["case_id"] for item in CASES}) != 80:
        raise SystemExit("duplicate case ids")
    if len({item["question"] for item in CASES}) != 80:
        raise SystemExit("duplicate questions")
    payload = {
        "dataset_id": DATASET_ID,
        "dataset_version": DATASET_ID,
        "corpus_version": "acmeai-v1",
        "generation_method": "manual-corpus-grounded-v1",
        "cases": CASES,
    }
    OUTPUT.write_text(json.dumps(payload, indent=2) + "\n")
    digest = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    overlap, per_file = maximum_prior_overlap()
    print(
        json.dumps(
            {
                "dataset_hash": digest,
                "maximum_prior_overlap": overlap,
                "per_file_overlap": per_file,
                "case_count": len(CASES),
            },
            indent=2,
        )
    )
    if overlap >= ACCEPTED_OVERLAP_CEILING:
        raise SystemExit("overlap guard failed")
    for name, ceiling in FROZEN_PRIOR_MAXIMA.items():
        if per_file.get(name, 0.0) > ceiling + 1e-12:
            raise SystemExit(f"new dataset would raise frozen overlap for {name}")


if __name__ == "__main__":
    main()
