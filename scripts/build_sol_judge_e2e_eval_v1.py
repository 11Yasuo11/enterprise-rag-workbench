def terms(question: str) -> set[str]:
    return set(re.findall(r"[a-z0-9]+", question.casefold()))


def main() -> None:
    payload = {
        "dataset_version": DATASET_ID,
        "corpus_version": "acmeai-v1",
        "cases": CASES,
    }
    OUTPUT.write_text(json.dumps(payload, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
    digest = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    token = re.compile(r"[a-z0-9]+")
    maximum = 0.0
    pair = ("", "", "")
    for path in Path("data/eval").glob("*.json"):
        if path == OUTPUT:
            continue
        for previous in json.loads(path.read_text()).get("cases", []):
            right = set(token.findall(previous["question"].casefold()))
            for case in CASES:
                left = set(token.findall(case["question"].casefold()))
                score = len(left & right) / len(left | right)
                if score > maximum:
                    maximum = score
                    pair = (case["case_id"], previous.get("case_id", path.name), previous["question"])
    print(f"hash={digest}")
    print(f"cases={len(CASES)}")
    print(f"max_overlap={maximum}")
    print(f"pair={pair[0]} vs {pair[1]}")
    print(f"old_question={pair[2]}")


if __name__ == "__main__":
    main()
