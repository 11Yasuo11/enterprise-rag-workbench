def overlap_report() -> dict[str, object]:
    maximum = 0.0
    closest: dict[str, object] | None = None
    per_file: dict[str, float] = {}
    for path in sorted(Path("data/eval").glob("*.json")):
        if path == OUTPUT:
            continue
        file_max = 0.0
        for previous in json.loads(path.read_text()).get("cases", []):
            right = terms(previous["question"])
            for item in CASES:
                left = terms(item["question"])
                union = left | right
                score = len(left & right) / len(union) if union else 0.0
                file_max = max(file_max, score)
                if score > maximum:
                    maximum = score
                    closest = {
                        "case_id": item["case_id"],
                        "prior_dataset": path.name,
                        "prior_case_id": previous.get("case_id"),
                        "overlap": score,
                    }
        per_file[path.name] = file_max
    return {
        "maximum_normalized_overlap": maximum,
        "closest_prior_case": closest,
        "per_file_overlap": per_file,
        "overlap_threshold": OVERLAP_CEILING,
        "pass": maximum < OVERLAP_CEILING,
    }


def main() -> None:
    distribution = {name: 0 for name in EXPECTED}
    for item in CASES:
        distribution[str(item["category"])] += 1
    if distribution != EXPECTED:
        raise SystemExit(f"category distribution drifted: {distribution}")
    if len(CASES) != 80:
        raise SystemExit(f"expected 80 cases, got {len(CASES)}")
    same_doc = [item for item in CASES if item["requires_multiple_chunks_same_document"]]
    if len(same_doc) < 8:
        raise SystemExit("need at least 8 same-document multi-chunk cases")
    ids = [str(item["case_id"]) for item in CASES]
    if len(set(ids)) != 80:
        raise SystemExit("duplicate case IDs")
    payload = {
        "dataset_id": DATASET_ID,
        "dataset_version": DATASET_ID,
        "corpus_version": "acmeai-v1",
        "generation_method": "manual-corpus-grounded-v1",
        "cases": CASES,
    }
    serialized = json.dumps(payload, indent=2, ensure_ascii=True) + "\n"
    OUTPUT.write_text(serialized)
    digest = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    overlap = overlap_report()
    print(
        json.dumps(
            {
                "dataset_hash": digest,
                "case_count": len(CASES),
                "distribution": distribution,
                "same_document_multi_chunk": len(same_doc),
                **overlap,
            },
            indent=2,
        )
    )
    if not overlap["pass"]:
        raise SystemExit("overlap guard failed")
    for name, ceiling in FROZEN_OVERLAP_CEILINGS.items():
        if overlap["per_file_overlap"].get(name, 0.0) > ceiling + 1e-12:
            raise SystemExit(f"new dataset would raise frozen overlap for {name}")


if __name__ == "__main__":
    main()
